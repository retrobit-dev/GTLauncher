const assert = require('node:assert/strict');
const blocks = require('../preview/block-stack.js');
const ground = [1];
const raised = blocks.add(ground, 2);
assert.deepEqual(ground, [1], 'editing does not mutate input');
assert.deepEqual(raised, [1, 2]);
assert.deepEqual(blocks.add([], 5), [5]);
assert.deepEqual(blocks.replaceTop(raised, 4), [1, 4]);
assert.deepEqual(blocks.removeTop(raised), [1]);
assert.equal(blocks.replaceTop([], 4), null);
assert.equal(blocks.removeTop([]), null);
assert.equal(blocks.add(Array(blocks.MAX_HEIGHT).fill(1), 1), null);
assert(blocks.canStep(ground, raised));
assert(blocks.canStep(raised, ground));
assert(!blocks.canStep(ground, [1, 2, 3]));
assert(!blocks.canStep(ground, []));
assert.throws(() => blocks.add([1, 0], 2), TypeError);
assert.throws(() => blocks.add(ground, 7), TypeError);
console.log('Block stack editing and one-level steps: OK');
